package hook

// hardeningRewriteCases are the streaming/interactive holes found by review of
// the coverage expansion, one declined spelling per reproduced hole plus the
// nearby finite spellings that must keep their coverage. Appended to
// TestRewrite's table (and so to FuzzRewrite's seeds).
func hardeningRewriteCases() []rewriteTestCase {
	var cases []rewriteTestCase
	wrap := func(cmd string) { cases = append(cases, rewriteTestCase{"wrap " + cmd, cmd, "sctx " + cmd, true}) }
	keep := func(cmd string) { cases = append(cases, rewriteTestCase{"decline " + cmd, cmd, cmd, false}) }

	// 1. playwright test is wrapped; the run side sets PLAYWRIGHT_HTML_OPEN=never.
	wrap("playwright test")
	wrap("npx playwright test")
	wrap("pnpm exec playwright test")

	// 2. rake: allowlist of first task.
	keep("rake")
	keep("rake jobs:work")
	keep("rake db:console")
	keep("rake server")
	keep("bundle exec rake")
	keep("bundle exec rake jobs:work")
	wrap("rake -T")
	wrap("rake --tasks")
	wrap("rake test")
	wrap("rake test:units")
	wrap("rake spec:models")
	wrap("rake db:migrate")
	wrap("rake assets:precompile")
	wrap("rake routes")
	wrap("rake log:clear")
	wrap("rake tmp:clear")
	wrap("rake build")
	wrap("bundle exec rake test")

	// 3. nx/turbo task operands.
	keep("nx run app:serve:development")
	keep("turbo run web#dev")
	keep("turbo run docs:dev")
	keep("turbo run develop")
	keep("nx run app:preview")
	keep("turbo run web#start")
	wrap("turbo run web#build")
	wrap("nx run app:build:production")

	// 4. quoted arguments.
	keep(`tail "-f" x`)
	keep(`tail '-f' x`)
	keep(`docker logs "-f" c`)
	keep(`kubectl logs "-f" p`)
	keep(`jest "--watch"`)
	keep(`bun test "--watch"`)
	keep(`playwright test "--ui"`)
	keep(`turbo run "dev"`)
	wrap(`tail -n 5 x`)

	// 5. podman watch.
	keep("podman ps --watch 2")
	keep("podman ps -w 2")
	keep("podman ps --watch=2")
	keep("podman container ls --watch")
	wrap("podman container ls")
	wrap("podman ps -a")

	// 6. lsof repeat mode.
	keep("lsof -nPr 2")
	keep("lsof -r1m==%T==")
	keep("lsof +r 3")
	keep("lsof -i :80 -r")
	wrap("lsof -nP -i :8080")

	// 7. ansible-playbook prompts.
	keep("ansible-playbook -bK site.yml")
	keep("ansible-playbook -kK site.yml")
	keep("ansible-playbook -J site.yml")
	keep("ansible-playbook --step site.yml")
	keep("ansible-playbook --ask-pass site.yml")
	keep("ansible-playbook --vault-id dev@prompt site.yml")
	keep("ansible-playbook --vault-id=dev@prompt site.yml")
	wrap("ansible-playbook --vault-id dev@vault.txt site.yml")
	wrap("ansible-playbook -i hosts -b site.yml")

	// 8. task/just namespaced recipes.
	keep("task docs:serve")
	keep("just build docs:serve")
	keep("task build docs:serve")
	wrap("task docs:build")
	wrap("just build docs:test")

	// 9. smaller holes.
	keep("phpstan analyse --pro")
	keep("phpstan analyse --fix")
	keep("ast-grep scan -iU")
	keep("ninja -t browse")
	keep("ninja -tbrowse")
	keep("ninja run")
	keep("cmake --build build --target run")
	keep("cmake --build build --target=run")
	wrap("cmake --build build --target all")
	keep("bun test --inspect")
	keep("bun test --inspect-brk")
	keep("deno test --inspect-wait")
	keep("ping -t -w 3 host")
	keep("ping -t host")
	wrap("ping -w 3 host")
	keep("oxlint --lsp")
	keep("sqlfluff fix q.sql")
	keep("sqlfluff fix --check -f q.sql")
	wrap("sqlfluff fix --force q.sql")

	// 11/12. launchers.
	keep("uv run ptw")
	keep("uv run pytest-watch")
	keep("poetry run ptw")
	keep("bundle exec jekyll serve")
	keep("bundle exec irb")
	keep("bundle exec pry")
	keep("bundle exec unicorn")
	keep("bundle exec thin start")
	keep("bundle exec rails console")
	keep("bundle exec rails db:migrate")
	keep("bundle exec tail -f x")
	keep("bundle exec --keep-file-descriptors puma")
	wrap("bundle exec rails test")
	wrap("bundle exec rubocop")

	// 13. cloud and JVM.
	keep("aws configure")
	keep("aws configure set region eu-west-1")
	keep("aws --profile p configure list")
	keep("aws logs start-live-tail --log-group-identifiers g")
	keep("aws ec2-instance-connect ssh --instance-id i-1")
	keep("aws ec2-instance-connect open-tunnel --instance-id i-1")
	keep("gcloud emulators firestore start")
	keep("gcloud run services proxy svc")
	keep("gcloud sql connect db")
	keep("gcloud init")
	keep("gcloud alpha interactive")
	keep("gcloud compute connect-to-serial-port vm")
	keep("gcloud workstations start-tcp-tunnel w 22")
	keep("gcloud beta code dev")
	keep("az ssh vm")
	keep("az webapp ssh -n x")
	keep("az container exec -n x")
	keep("az container attach -n x")
	keep("az containerapp exec -n x")
	keep("az aks browse -n x")
	keep("az webapp create-remote-connection -n x")
	keep("az network bastion tunnel -n x")
	keep("az serial-console connect -n x")
	keep("az containerapp logs show -n x -f")
	keep("az devops login")
	keep("az account login")
	keep("terraform login")
	keep("terraform force-unlock abc")
	wrap("terraform force-unlock -force abc")
	keep("terragrunt run-all apply -auto-approve")
	wrap("terragrunt run-all apply --terragrunt-non-interactive")
	keep("terragrunt run-all destroy")
	keep("gradle -q run")
	keep("gradle :sub:jettyRun")
	keep("gradle :app:appRunWar")
	keep("gradle tomcatRunWar")
	keep("gradle bootR")
	keep("gradle bRu")
	keep("gradle runClient")
	keep("gradle jettyRunWar")
	wrap("gradle build")
	wrap("gradle bootJar")
	wrap("gradle :app:test")
	keep("mvn spring-boot:run@dev")
	keep("mvn quarkus:dev@x")
	keep("mvn quarkus:test")
	keep("mvn foo:dev")
	keep("mvn foo:devmode")
	keep("mvn foo:watch")
	keep("mvn foo:console")
	keep("mvn foo:shell")
	keep("mvn foo:start")
	keep("mvn foo:run-war")
	keep("mvn foo:test-run")
	wrap("mvn dependency:tree")
	wrap("mvn surefire:test")
	return cases
}
